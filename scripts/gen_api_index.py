"""Generate API.md: a compact index of lib-utils' public API (signatures only, no bodies).

One line per public class / function / method: source line, signature and a one-line summary
(the docstring's first paragraph, else the comment block right above the def). Lets a reader -
human or AI assistant - find a helper and jump to its source line without reading whole modules.

Usage (from anywhere; stdlib only):
    python scripts/gen_api_index.py            # (re)write API.md
    python scripts/gen_api_index.py --check    # exit 1 if API.md is out of date (for a git hook / CI)
"""
from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / 'utils'
OUT = ROOT / 'API.md'

MAX_DEFAULT = 24     # longer default values are shown as '…'
MAX_PARAMS = 8       # more parameters are cut to the first MAX_PARAMS + '…' (full signature: the source line)
MAX_SUMMARY = 110    # summary characters per entry
# Parameter annotations are left out to keep the index small (return annotations are kept);
# the line number takes you to the full signature.
SKIP_METHODS = {'lib_demo'}
SKIP_FILES = {'utils/demo.py'}   # the interactive demo notebook, not importable API
UI_CLASS_SUFFIX = 'GUI'           # tool UI classes: listed, but their methods (widget callbacks) are not
DIVIDER_PREFIXES = ('──', '--', '==', '##', '**')  # section-divider comments, e.g. '# ── helpers ────'
STDLIB = set(sys.stdlib_module_names) | {'__future__'}

HEADER = """\
# lib-utils API index

Generated by `scripts/gen_api_index.py` - do not edit by hand; rerun it after changing the public API.
Each `##` heading is a source file (relative to lib-utils/; import path = the path with dots).
Entries: `L<line>  name(params) -> return  - summary`. Methods are indented under their class.
Parameter types are omitted and long parameter lists end in `…`: read the source line for the full signature.
[needs: ...] lists a module's third-party imports; [stdlib] means none.
Tool UI classes (`*GUI`) are listed without their methods (widget callbacks): use the module's show_gui().

Core: `from utils import UtilityFunctions; utils = UtilityFunctions()` - every method of the
`utils/_internal` mixins below is available on `utils`. Non-mixin classes in `_internal` and
`utilities.py` are importable from `utils` directly. `standalone` and `tools` modules are imported
explicitly, e.g. `from utils.standalone.sqlite_utils import SQLite`.
"""


# ---------------------------------------------------------------- text helpers

def shorten(text: str, limit: int = MAX_SUMMARY) -> str:
    text = ' '.join(text.split())
    if len(text) <= limit:
        return text
    sentence_end = text.find('. ', 0, limit)
    while sentence_end != -1 and text[:sentence_end].endswith(('e.g', 'i.e', 'etc', 'vs')):
        sentence_end = text.find('. ', sentence_end + 2, limit)  # an abbreviation, not a sentence end
    if sentence_end >= 30:
        return text[:sentence_end + 1]
    return text[:limit].rsplit(' ', 1)[0].rstrip(',;:') + '…'


def comment_above(lines: list[str], lineno: int) -> str:
    """The contiguous '#' comment block ending right above 1-based line `lineno`."""
    i = lineno - 2
    block = []
    while i >= 0 and lines[i].strip().startswith('#'):
        text = lines[i].strip().lstrip('# ')
        if text.startswith(DIVIDER_PREFIXES):
            break  # a section divider ends the function's own comment block
        block.append(text)
        i -= 1
    return ' '.join(reversed([b for b in block if b]))


def summary(node, lines: list[str]) -> str:
    doc = ast.get_docstring(node, clean=True)
    if doc:
        return shorten(doc.strip().split('\n\n')[0])
    first = node.decorator_list[0].lineno if node.decorator_list else node.lineno
    return shorten(comment_above(lines, first))


def module_summary(tree: ast.Module, lines: list[str]) -> str:
    doc = ast.get_docstring(tree, clean=True)
    if doc:
        return shorten(doc.strip().split('\n\n')[0], 200)
    block = []
    for line in lines:
        s = line.strip()
        if not s.startswith('#'):
            break
        text = s.lstrip('# ')  # also strips jupytext markdown headings ('# ## Title')
        if text and not text.endswith('.py') and not text.startswith('%%'):  # skip '# utils/x.py', cell markers
            block.append(text)
    return shorten(' '.join(block), 200)


# ---------------------------------------------------------------- signatures

def fmt_arg(arg: ast.arg, default) -> str:
    s = arg.arg
    if default is not None:
        d = ast.unparse(default)
        s += '=' + (d if len(d) <= MAX_DEFAULT else '…')
    return s


def fmt_args(a: ast.arguments, drop_self: bool) -> str:
    pos = a.posonlyargs + a.args
    defaults = [None] * (len(pos) - len(a.defaults)) + list(a.defaults)
    start = 1 if drop_self and pos and pos[0].arg in ('self', 'cls') else 0
    parts = []
    for i in range(start, len(pos)):
        parts.append(fmt_arg(pos[i], defaults[i]))
        if a.posonlyargs and i == len(a.posonlyargs) - 1:
            parts.append('/')
    if a.vararg:
        parts.append('*' + fmt_arg(a.vararg, None))
    elif a.kwonlyargs:
        parts.append('*')
    parts += [fmt_arg(arg, d) for arg, d in zip(a.kwonlyargs, a.kw_defaults)]
    if a.kwarg:
        parts.append('**' + fmt_arg(a.kwarg, None))
    return cap(parts)


def cap(parts: list[str]) -> str:
    return ', '.join(parts if len(parts) <= MAX_PARAMS else parts[:MAX_PARAMS] + ['…'])


def decorator_names(node) -> set[str]:
    return {ast.unparse(d).split('(')[0].split('.')[-1] for d in node.decorator_list}


def fmt_func(node, in_class: bool) -> str:
    decos = decorator_names(node)
    ret = f' -> {ast.unparse(node.returns)}' if node.returns is not None else ''
    if 'property' in decos or 'cached_property' in decos:
        return f'{node.name}{ret}  (property)'
    prefix = 'async ' if isinstance(node, ast.AsyncFunctionDef) else ''
    if 'staticmethod' in decos:
        prefix += '@staticmethod '
    elif 'classmethod' in decos:
        prefix += '@classmethod '
    return f'{prefix}{node.name}({fmt_args(node.args, drop_self=in_class)}){ret}'


def fmt_class(node: ast.ClassDef) -> str:
    decos = decorator_names(node)
    bases = [ast.unparse(b) for b in node.bases]
    fields = [n for n in node.body if isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name)]
    init = next((n for n in node.body if isinstance(n, ast.FunctionDef) and n.name == '__init__'), None)
    if init is not None:
        sig = fmt_args(init.args, drop_self=True)
    elif fields and ('dataclass' in decos or 'NamedTuple' in bases or 'TypedDict' in bases):
        sig = cap([fmt_arg(ast.arg(f.target.id), f.value) for f in fields])
    else:
        sig = ''
    shown_bases = [b for b in bases if b not in ('object', 'NamedTuple')]
    base_txt = f'  [bases: {", ".join(shown_bases)}]' if shown_bases and len(shown_bases) <= 3 else ''
    kind = 'dataclass' if 'dataclass' in decos else 'class'
    return f'{kind} {node.name}({sig}){base_txt}'


# ---------------------------------------------------------------- modules

def third_party_imports(tree: ast.Module) -> list[str]:
    names = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            names.update(a.name.split('.')[0] for a in n.names)
        elif isinstance(n, ast.ImportFrom) and n.level == 0 and n.module:
            names.add(n.module.split('.')[0])
    return sorted(n for n in names if n not in STDLIB and n != 'utils')


def relative_reexports(init_tree: ast.Module) -> dict[str, set[str]]:
    """{private module stem: names that the package __init__ imports from it}."""
    out: dict[str, set[str]] = {}
    for n in init_tree.body:
        if isinstance(n, ast.ImportFrom) and n.level == 1 and n.module:
            out.setdefault(n.module, set()).update(a.asname or a.name for a in n.names)
    return out


def entries(tree: ast.Module, lines: list[str], only: set[str] | None) -> list[str]:
    out = []

    def public(name: str) -> bool:
        return not name.startswith('_') and (only is None or name in only)

    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and public(node.name):
            out.append(line(node.lineno, fmt_func(node, in_class=False), summary(node, lines), 0))
        elif isinstance(node, ast.ClassDef) and public(node.name):
            out.append(line(node.lineno, fmt_class(node), summary(node, lines), 0))
            if node.name.endswith(UI_CLASS_SUFFIX):
                continue  # UI class: its methods are widget callbacks; use the module's show_gui()
            for m in node.body:
                if (isinstance(m, (ast.FunctionDef, ast.AsyncFunctionDef))
                        and not m.name.startswith('_') and m.name not in SKIP_METHODS):
                    out.append(line(m.lineno, fmt_func(m, in_class=True), summary(m, lines), 1))
    return out


def line(lineno: int, sig: str, desc: str, indent: int) -> str:
    text = f'L{lineno:<5}{"  " * indent}{sig}'
    return f'{text}  - {desc}' if desc else text


def sort_key(path: Path):
    rel = path.relative_to(PKG).as_posix()
    order = ['utilities.py', '_internal/', 'standalone/', 'tools/']
    rank = next((i for i, p in enumerate(order) if rel.startswith(p)), len(order))
    return rank, rel


def top_names(tree: ast.Module, only: set[str] | None, limit: int = 6) -> str:
    names = [n.name for n in tree.body
             if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
             and not n.name.startswith('_') and (only is None or n.name in only)]
    return ', '.join(names[:limit]) + (f', … (+{len(names) - limit})' if len(names) > limit else '')


def build() -> tuple[str, dict]:
    sections = []  # (toc line without range, section lines)
    stats = {'modules': 0, 'entries': 0, 'source_bytes': 0}
    files = sorted(PKG.rglob('*.py'), key=sort_key)
    for path in files:
        if '__pycache__' in path.parts or path.relative_to(ROOT).as_posix() in SKIP_FILES:
            continue
        source = path.read_text(encoding='utf-8-sig')
        stats['source_bytes'] += len(source.encode('utf-8'))
        stem = path.stem
        only = None
        note = ''
        if stem.startswith('_') and stem != '__init__':
            init = path.parent / '__init__.py'
            if not init.exists():
                continue
            names = relative_reexports(ast.parse(init.read_text(encoding='utf-8-sig'))).get(stem)
            if not names:
                continue  # private helper module, nothing re-exported
            only = names
            pkg_dotted = path.parent.relative_to(ROOT).as_posix().replace('/', '.')
            note = f'  (re-exported by {pkg_dotted})'
        try:
            tree = ast.parse(source, filename=str(path))
        except SyntaxError as e:
            print(f'warning: skipped {path}: {e}', file=sys.stderr)
            continue
        lines = source.splitlines()
        body = entries(tree, lines, only)
        if not body:
            continue
        deps = third_party_imports(tree)
        deps_txt = f'[needs: {", ".join(deps)}]' if deps else '[stdlib]'
        rel = path.relative_to(ROOT).as_posix()
        block = [f'## {rel}  {deps_txt}{note}']
        mod_doc = module_summary(tree, lines) if only is None else ''
        if mod_doc:
            block.append(mod_doc)
        block += ['```', *body, '```', '']
        toc = f'{rel}  {deps_txt}  {{range}}  {top_names(tree, only)}'
        if mod_doc:
            toc += f'  - {shorten(mod_doc, 80)}'
        sections.append((toc, block))
        stats['modules'] += 1
        stats['entries'] += len(body)

    # Table of contents with each section's line range in this file, so a reader can read the
    # contents first and then only the section it needs (Read with offset/limit).
    head = HEADER.rstrip('\n').split('\n') + ['', '## Contents (path  [deps]  API.md lines  top-level names)', '```']
    first_section_line = len(head) + len(sections) + 3  # + toc lines, closing fence, blank line; 1-based
    toc_lines, body_lines, line_no = [], [], first_section_line
    for toc, block in sections:
        end = line_no + len(block) - 2  # last line = closing fence
        toc_lines.append(toc.replace('{range}', f'L{line_no}-{end}'))
        body_lines += block
        line_no += len(block)
    text = '\n'.join(head + toc_lines + ['```', ''] + body_lines)
    return text.rstrip('\n') + '\n', stats


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 if API.md is out of date, write nothing')
    args = parser.parse_args()

    text, stats = build()
    current = OUT.read_text(encoding='utf-8') if OUT.exists() else None
    if args.check:
        if current != text:
            print('API.md is out of date - run: python scripts/gen_api_index.py', file=sys.stderr)
            return 1
        print('API.md is up to date')
        return 0

    if current != text:
        OUT.write_text(text, encoding='utf-8', newline='\n')
    out_bytes = len(text.encode('utf-8'))
    print(f'{"wrote" if current != text else "unchanged"} {OUT.name}: {stats["modules"]} modules, '
          f'{stats["entries"]} entries, {out_bytes / 1024:.1f} KB '
          f'({out_bytes / stats["source_bytes"]:.0%} of {stats["source_bytes"] / 1024:.0f} KB source)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
